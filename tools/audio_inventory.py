#!/usr/bin/env python3
"""Inventory reviewed Sound_Player exports and direct genuine-test references."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    spec = (ROOT / "docs/specs/stdlib/modules/sound-player.md").read_text()
    inventory = spec.split("## Public aggregate shapes")[0]
    files = [ROOT / "stdlib/Sound_Player/module.jai"]
    files += sorted(p for p in (ROOT / "stdlib/internal/audio").glob("*.jai") if p.name != "wav.jai")
    tests = sorted((ROOT / "tests/audio").glob("*.jai"))
    tests += [ROOT / "tests/stdlib/sound-player-device.jai"]
    rows = []
    missing = set()
    for line in inventory.splitlines():
        match = re.match(r"- (?:\[(.*?)\] )?`(.*?)`", line)
        if not match:
            continue
        condition, signature = match.groups()
        name_match = re.match(r"(\w+)", signature)
        if not name_match:
            continue
        name = name_match.group(1)
        declarations = [p for p in files if re.search(r"(?m)^\s*(?:#if[^\n]*?\s+)?"
                        + re.escape(name) + r"\s*(?:::|:=|:)", p.read_text())]
        refs = [p.stem for p in tests if p.stem != "signatures" and re.search(r"\b" + re.escape(name) + r"\b", p.read_text())]
        signature_probe = re.search(r"\b" + re.escape(name) + r"\b", (ROOT / "tests/audio/signatures.jai").read_text())
        if not declarations:
            missing.add(name)
        source = ", ".join(p.name for p in declarations) or "**missing contract/implementation**"
        evidence = ", ".join(refs) if refs else "no direct genuine-test reference"
        if signature_probe:
            evidence += "; signature/link probe (not behavioral evidence)"
        if condition and "WINDOWS" in condition:
            evidence += "; Windows branch checked only (no Windows native execution)"
        rows.append((name, condition or "common", source, evidence))
    rows.sort()
    text = "# Sound_Player public API implementation and genuine-test inventory\n\n"
    text += "Generated by tools/audio_inventory.py from reviewed inventory and this worker's\n"
    text += "NEW source/tests. Presence is not proof of behavior; direct test references are\n"
    text += "listed without claiming that every branch was executed. See progress for actual\n"
    text += "interpreter/native/target evidence. Windows runtime branches are source-only.\n\n"
    text += f"Reviewed declaration rows: {len(rows)}. Missing names: {', '.join(sorted(missing)) or 'none'}.\n\n"
    text += "| Public name | Condition | Implementation unit | Direct genuine-test reference |\n"
    text += "| --- | --- | --- | --- |\n"
    for row in rows:
        text += "| " + " | ".join(row) + " |\n"
    (ROOT / "docs/status/audio-api-inventory.md").write_text(text)
    print(f"Inventoried {len(rows)} reviewed declaration rows; missing: {', '.join(sorted(missing)) or 'none'}")


if __name__ == "__main__":
    main()
